import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const projectRoot = resolve(new URL("..", import.meta.url).pathname);
const gallerySourcePath = resolve(projectRoot, "client/src/pages/Gallery.tsx");
const imageSitemapPath = resolve(projectRoot, "client/public/gallery-image-sitemap.xml");
const imageIndexPath = resolve(projectRoot, "api/_knowledge/galleryImages.js");
const siteUrl = "https://www.mahbubsardarsabuj.com";

function escapeXml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function toAbsoluteUrl(value) {
  return value.startsWith("http") ? value : new URL(value, siteUrl).toString();
}

const gallerySource = readFileSync(gallerySourcePath, "utf8");
const constants = Object.fromEntries(
  [...gallerySource.matchAll(/^const\s+([A-Z0-9_]+)\s+=\s+"([^"]+)";/gm)].map(([, name, value]) => [name, value])
);

const galleryBlock = gallerySource.match(/const galleryImages(?:\s*:\s*GalleryImage\[\])?\s*=\s*\[([\s\S]*?)\]\.(?:sort|map)/);
if (!galleryBlock) throw new Error("galleryImages array was not found in Gallery.tsx");

const images = [...galleryBlock[1].matchAll(/\{\s*src:\s*([^,]+),\s*caption:\s*"([^"]+)"(?:,\s*addedAt:\s*"([^"]+)")?\s*\}/g)].map(([, rawSource, caption, addedAt]) => {
  const source = rawSource.trim();
  const sourceValue = source.startsWith('"') ? source.slice(1, -1) : constants[source];
  if (!sourceValue) throw new Error(`Unresolved gallery image source: ${source}`);
  return { src: toAbsoluteUrl(sourceValue), caption, addedAt };
}).sort((first, second) => {
  const firstAddedAt = first.addedAt ? Date.parse(first.addedAt) : 0;
  const secondAddedAt = second.addedAt ? Date.parse(second.addedAt) : 0;
  return secondAddedAt - firstAddedAt;
});

if (images.length < 1) throw new Error("No gallery images were parsed");
if (new Set(images.map((image) => image.src)).size !== images.length) {
  throw new Error("Gallery contains duplicate image URLs; use one canonical URL per visual asset");
}

const updatedAt = new Date().toISOString().slice(0, 10);
const imageSitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">\n  <url>\n    <loc>${siteUrl}/gallery</loc>\n    <lastmod>${updatedAt}</lastmod>\n${images.map(({ src }) => `    <image:image><image:loc>${escapeXml(src)}</image:loc></image:image>`).join("\n")}\n  </url>\n</urlset>\n`;

const imageIndex = `// Generated by scripts/generate-gallery-image-seo.mjs from client/src/pages/Gallery.tsx.\n// Run pnpm seo:gallery after changing galleryImages.\nexport const galleryImages = ${JSON.stringify(images, null, 2)};\nexport const galleryPrimaryImage = galleryImages[0]?.src;\n`;

writeFileSync(imageSitemapPath, imageSitemap);
writeFileSync(imageIndexPath, imageIndex);
console.log(`Generated image SEO index and sitemap for ${images.length} gallery images.`);
